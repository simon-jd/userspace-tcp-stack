// Linux TUN interface opened with IFF_TUN | IFF_NO_PI: each read returns one
// IP packet by default. Offload modes prefix it with a virtio_net_hdr.
#pragma once

#include <chrono>
#include <cstddef>
#include <cstdint>
#include <optional>
#include <expected>
#include <span>
#include <string>
#include <string_view>
#include <system_error>
#include <utility>

#include "utcp/packet.hpp"

namespace utcp {

enum class TunOffload { legacy, checksum, tcpv4 };
[[nodiscard]] constexpr std::string_view to_string(TunOffload offload) noexcept {
  switch (offload) {
    case TunOffload::legacy: return "legacy";
    case TunOffload::checksum: return "checksum";
    case TunOffload::tcpv4: return "tcpv4";
  }
  return {};
}

// IFF_VNET_HDR with the 10-byte Linux virtio-net ABI in little-endian mode.
inline constexpr std::size_t tun_vnet_header_size = 10;
inline constexpr std::size_t tun_max_queues = 64;

// Select the transmit queue from the outgoing TCP four-tuple, before
// adding any VNET header. Non-TCP output goes to queue zero.
// Precondition: count > 0.
[[nodiscard]] std::size_t tun_tx_queue(std::span<const std::byte> ip, std::size_t count) noexcept;

struct TunRxPacket {
  std::span<const std::byte> ip;
  RxMeta meta;
  std::uint32_t segments = 1;
};

// Validate the kernel frame before granting checksum trust to the core.
[[nodiscard]] std::optional<TunRxPacket> decode_tun_vnet(
    std::span<const std::byte> frame, TunOffload offload) noexcept;
// Adds the header in PacketBuf headroom. Returns the number of logical
// segments. Requires a valid IPv4 TxPacket generated by the Stack.
std::uint32_t prepend_tun_vnet(TxPacket& packet) noexcept;

class TunDevice {
public:
  // Opens /dev/net/tun and attaches to interface `name`, creating it if it
  // does not exist (creating needs CAP_NET_ADMIN). An empty name lets the
  // kernel pick one (tun0, tun1, ...). The interface is left down and without
  // an address. Use multi_queue for each independent fd of a multi-queue interface.
  static std::expected<TunDevice, std::error_code> open(
      std::string_view name, bool nonblocking, TunOffload offload = TunOffload::legacy,
      bool multi_queue = false);

  TunDevice(TunDevice&& other) noexcept;
  TunDevice& operator=(TunDevice&& other) noexcept;
  TunDevice(const TunDevice&) = delete;
  TunDevice& operator=(const TunDevice&) = delete;
  ~TunDevice();

  [[nodiscard]] int fd() const noexcept { return fd_; }
  // Gives up the file descriptor: the caller closes it. The device object is
  // left without one (fd() == -1).
  [[nodiscard]] int release() noexcept { return std::exchange(fd_, -1); }
  // Name the kernel assigned.
  [[nodiscard]] const std::string& name() const noexcept { return name_; }

  // The header size that was read back from the TUN fd, or zero in legacy mode.
  [[nodiscard]] std::size_t vnet_header_size() const noexcept { return vnet_header_size_; }

  // Reads one raw TUN frame. A shorter buffer truncates it.
  std::expected<std::size_t, std::error_code> read(std::span<std::byte> buf) const;
  // Writes one raw TUN frame.
  std::expected<std::size_t, std::error_code> write(std::span<const std::byte> packet) const;

  // The interface's operational state, /sys/class/net/<name>/operstate
  // without the newline ("up", "down", ...); empty if it cannot be read.
  [[nodiscard]] std::string operstate() const;
  // Waits until operstate() is "up", polling every 100 us for at most `max`,
  // then 1 ms more. Attaching to an interface turns its carrier on, but until
  // the kernel's link watcher has re-enabled the qdisc (right after it sets
  // operstate to "up"), packets the kernel sends to the interface are dropped
  // and counted as TX dropped. An interface that is administratively down
  // never gets there. Returns whether it did.
  [[nodiscard]] bool wait_running(std::chrono::nanoseconds max) const;

private:
  TunDevice(int fd, std::string name, std::size_t header_size) noexcept
      : fd_(fd), name_(std::move(name)), vnet_header_size_(header_size) {}

  int fd_ = -1;
  std::string name_;
  std::size_t vnet_header_size_ = 0;
};

}  // namespace utcp
